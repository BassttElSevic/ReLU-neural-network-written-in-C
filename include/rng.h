#ifndef RNG_H
#define RNG_H

/* =====================================================================
 * 随机数工具:包装 C 标准库的 rand()。
 * 用于随机生成样本的位置、大小,以及初始化权重。
 * ===================================================================== */

/* 设置随机数种子。
 * 设固定种子可以让每次运行得到同样的随机序列,结果可复现。 */
void rng_seed(int seed);

/* 返回 [low, high) 内的随机整数(不含 high)。 */
int  rand_range(int low, int high);

#endif /* RNG_H */
